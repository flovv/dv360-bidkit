def test_inventory_expiry_and_targeting_block_extraction(tmp_path):
    from dv360_bidkit.io.inventory import extract_targeting_block_requests, load_inventory_policy

    csv_file = tmp_path / "policy_expiry.csv"
    csv_file.write_text(
        "entity_type,entity_value,action,source,as_of,expiry,score,label\n"
        "domain,expired-deal.com,set_score,deal,2026-01-01,2025-12-31,15.0,Old Deal\n"
        "domain,active-deal.com,set_score,deal,2026-01-01,2026-12-31,20.0,Active Deal\n"
        "domain,blockme.com,targeting_block_request,brand_safety,2026-01-01,,0.0,Block Ad Serving\n",
        encoding="utf-8",
    )

    policy = load_inventory_policy(csv_file, reference_date="2026-06-01")
    assert policy.normalization_metadata["expired_entries_skipped"] == 1
    assert len(policy.entries) == 2
    entities = {e.entity_value for e in policy.entries}
    assert "expired-deal.com" not in entities
    assert "active-deal.com" in entities

    blocks = extract_targeting_block_requests(policy)
    assert len(blocks) == 1
    assert blocks[0].entity_value == "blockme.com"


def test_messy_dv360_report_ingestion(tmp_path):
    """Verify preamble skipping, summary footer stripping, locale numbers, and German header aliases."""
    from dv360_bidkit.contracts.schemas import ReportMapping
    from dv360_bidkit.io.reports import load_report

    csv_file = tmp_path / "messy_dv360_export.csv"
    csv_file.write_text(
        "Report Time:,2026-01-20 10:00:00\n"
        "Date Range:,Last 30 Days\n"
        "Advertiser:,Test GmbH\n"
        "\n"
        "Website,Impressionen,Active View: Messbare Impressionen,Active View: Sichtbare Impressionen,Mediakosten (Währung des Werbetreibenden)\n"
        'spiegel.de,"12,000","10,000","7,500","€45.50"\n'
        'zeit.de,"8,000","7,000","5,600","€30.00"\n'
        'Gesamt,"20,000","17,000","13,100","€75.50"\n'
        "Report generated by Display & Video 360,,,,\n",
        encoding="utf-8",
    )

    mapping = ReportMapping(
        canonical_field_map={
            "domain": "App/URL",
            "impressions": "Impressions",
            "measurable_impressions": "Active View: Measurable Impressions",
            "viewable_impressions": "Active View: Viewable Impressions",
            "cost": "Media Cost",
        }
    )

    rep = load_report(csv_file, mapping=mapping)
    assert rep.row_count == 2
    assert rep.metadata["preamble_rows_skipped"] == 4
    assert rep.metadata["footer_rows_stripped"] >= 1
    imp_col = rep.mapping.canonical_field_map["impressions"]
    assert int(rep.df[imp_col].sum()) == 20000
