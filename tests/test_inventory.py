"""Unit tests for inventory normalization, boundary matching, and conflict handling."""

import pytest
from dv360_bidkit.contracts.exceptions import InventoryPolicyError
from dv360_bidkit.contracts.schemas import (
    InventoryAction,
    InventoryEntityType,
    InventoryPolicy,
    InventoryPolicyConfig,
    InventoryPolicyEntry,
)
from dv360_bidkit.io.inventory import match_inventory_entity, normalize_domain


def test_normalize_domain_valid():
    assert normalize_domain("  SPIEGEL.DE  ") == "spiegel.de"
    assert normalize_domain("www.zeit.de", strip_www=True) == "zeit.de"
    assert normalize_domain("sub.example.com:8080") == "sub.example.com"
    assert normalize_domain("münchen.de") == "xn--mnchen-3ya.de"


def test_normalize_domain_rejects_paths():
    with pytest.raises(InventoryPolicyError, match="contains URL paths|contains path"):
        normalize_domain("example.com/some/path")


def test_subdomain_boundary_matching():
    policy = InventoryPolicy(
        entries=[
            InventoryPolicyEntry(
                entity_type=InventoryEntityType.DOMAIN,
                entity_value="example.com",
                action=InventoryAction.EXCLUDE_FROM_TRAINING,
                source="test",
                as_of="2026-01-01",
            )
        ],
        config=InventoryPolicyConfig(allow_subdomains=True),
    )

    # Matches exact
    m1 = match_inventory_entity("example.com", InventoryEntityType.DOMAIN, policy)
    assert m1 is not None

    # Matches subdomain with dot boundary
    m2 = match_inventory_entity("sub.example.com", InventoryEntityType.DOMAIN, policy)
    assert m2 is not None

    # Does NOT match without dot boundary
    m3 = match_inventory_entity("badexample.com", InventoryEntityType.DOMAIN, policy)
    assert m3 is None


