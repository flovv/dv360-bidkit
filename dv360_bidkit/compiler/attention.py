"""Concave Attention + Outcome DV360 Custom Bidding Compiler & MFA Stress-Test.

Generates zero-fee, Google DV360 DSL-compliant Python scripts combining:
1. Explicit if-capped time_on_screen_seconds (<= 20s default; no disallowed min/max).
2. Concave logarithmic decay log(_capped_t + 1.0) reflecting empirical saturation
   curves (Simonov, Valletti & Veiga, JMR 2025; Uhl et al., 2020).
3. Eye-tracking-calibrated format-anatomy multipliers (inline mobile 300x250/300x600
   and desktop ATF 970x250 upweighted; low-dwell 320x50 strips and BTF penalized).
4. Optional video audible-completion bonus (completed_in_view_audible).
5. Floodlight / GA4 conversion (or click) outcome anchor per IAB/MRC & ARF Phase 3.
6. Optional upstream MFA domain exclusions.

Also includes a deterministic MFA Sticky-Slot Stress-Test comparing four bidding
policies (vCPM, Naive Uncapped Linear Dwell, Concave Capped, and Concave Capped +
MFA Exclusion) using dv360-bidkit's safe ASTInterpreter.
"""

from __future__ import annotations

from typing import Any
from pydantic import BaseModel, Field

from dv360_bidkit.evaluator.interpreter import create_interpreter
from dv360_bidkit.linter.ast_validator import lint_script


class ConcaveAttentionConfig(BaseModel):
    """Configuration for compiling a zero-fee DV360 concave attention + outcome script."""

    dwell_cap_seconds: float = Field(default=20.0, gt=0.0, le=60.0)
    attention_weight: float = Field(default=1.0, gt=0.0)
    video_audible_bonus: float = Field(default=1.5, ge=0.0)

    # Outcome anchors (at least one recommended to avoid standalone attention traps)
    floodlight_activity_id: int | None = None
    attribution_model_id: int = 0
    conversion_weight: float = Field(default=25.0, ge=0.0)
    use_conversion_value: bool = False
    ga4_property_id: int | None = None
    ga4_event_name: str | None = None
    include_click_fallback: bool = True
    click_weight: float = Field(default=2.0, ge=0.0)

    # Format anatomy multipliers calibrated to empirical eye-tracking prominence
    billboard_multiplier: float = Field(default=1.5, gt=0.0)       # 970x250 ATF desktop
    half_page_multiplier: float = Field(default=1.4, gt=0.0)       # 300x600
    mobile_inline_multiplier: float = Field(default=1.3, gt=0.0)   # 300x250 mobile
    desktop_mpu_multiplier: float = Field(default=1.1, gt=0.0)     # 300x250 ATF desktop
    mobile_strip_multiplier: float = Field(default=0.5, gt=0.0)    # 320x50 mobile banner
    below_fold_multiplier: float = Field(default=0.7, gt=0.0)      # ad_position == 2

    # Optional upstream MFA domain exclusion list (web display/OLV only; omitted for CTV)
    excluded_domains: list[str] = Field(default_factory=list)


def compile_concave_attention_script(
    config: ConcaveAttentionConfig | None = None,
    *,
    validate: bool = True,
) -> str:
    """Compiles a zero-fee, DV360 DSL-compliant concave attention + outcome script."""
    cfg = config or ConcaveAttentionConfig()

    lines: list[str] = [
        "# Zero-Fee Concave Attention + Outcome DV360 Custom Bidding Script",
        "# Generated by dv360-bidkit (Simonov et al. 2025 concave saturation + IAB/MRC outcome anchor)",
        "",
    ]

    if cfg.excluded_domains:
        cleaned = sorted({d.strip().lower() for d in cfg.excluded_domains if d.strip()})
        domain_list_literal = "[" + ", ".join(repr(d) for d in cleaned) + "]"
        lines.extend([
            "# 1. Upstream MFA / low-attention domain exclusion",
            f"if domain in {domain_list_literal}:",
            "    return 0.0",
            "",
        ])

    cap = round(cfg.dwell_cap_seconds, 2)
    lines.extend([
        "# 2. Concave capped time-on-screen score (no disallowed min/max)",
        f"_capped_t = {cap} if time_on_screen_seconds > {cap} else time_on_screen_seconds",
        "_safe_t = 0.0 if _capped_t < 0.0 else _capped_t",
        "_dwell_score = log(_safe_t + 1.0) if active_view_viewed else 0.0",
        "",
        "# 3. Eye-tracking-calibrated format & fold multipliers",
        "_fmt_mult = 1.0",
        f"if creative_width == 970 and creative_height == 250 and ad_position == 1:",
        f"    _fmt_mult = {cfg.billboard_multiplier}",
        f"elif creative_width == 300 and creative_height == 600:",
        f"    _fmt_mult = {cfg.half_page_multiplier}",
        f"elif device_type == 2 and creative_width == 300 and creative_height == 250:",
        f"    _fmt_mult = {cfg.mobile_inline_multiplier}",
        f"elif device_type == 0 and creative_width == 300 and creative_height == 250 and ad_position == 1:",
        f"    _fmt_mult = {cfg.desktop_mpu_multiplier}",
        f"elif creative_width == 320 and creative_height == 50:",
        f"    _fmt_mult = {cfg.mobile_strip_multiplier}",
        "if ad_position == 2:",
        f"    _fmt_mult = _fmt_mult * {cfg.below_fold_multiplier}",
        "",
        "# 4. Video audible-completion bonus",
        f"_video_bonus = {cfg.video_audible_bonus} if completed_in_view_audible else 0.0",
        f"_attention_score = (_dwell_score * _fmt_mult + _video_bonus) * {cfg.attention_weight}",
        "",
        "# 5. Outcome anchor (Floodlight / GA4 / click fallback)",
    ])

    outcome_terms: list[str] = []
    if cfg.floodlight_activity_id is not None:
        fn = "total_conversion_value" if cfg.use_conversion_value else "total_conversion_count"
        outcome_terms.append(
            f"({fn}({cfg.floodlight_activity_id}, {cfg.attribution_model_id}) * {cfg.conversion_weight})"
        )
    if cfg.ga4_property_id is not None and cfg.ga4_event_name:
        outcome_terms.append(
            f"(ga4_conversions_count({cfg.ga4_property_id}, {cfg.ga4_event_name!r}) * {cfg.conversion_weight})"
        )
    if not outcome_terms and cfg.include_click_fallback:
        outcome_terms.append(f"({cfg.click_weight} if click else 0.0)")

    if outcome_terms:
        lines.append("_outcome_score = " + " + ".join(outcome_terms))
        lines.append("return _attention_score + _outcome_score")
    else:
        lines.append("return _attention_score")

    script = "\n".join(lines) + "\n"

    if validate:
        report = lint_script(script)
        if not report.is_valid:
            errors = "; ".join(f"{d.code}: {d.message}" for d in report.diagnostics)
            raise ValueError(f"Generated concave attention script failed AST validation: {errors}")

    return script


