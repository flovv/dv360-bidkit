def _simulate_strategy(
    name: str,
    script_code: str,
    budget: float,
    vcpm_cost_per_1k_s: float | None = None,
) -> MfaStressTestStrategyResult:
    interp = create_interpreter(script_code)

    # Compute value-per-euro weights across supply tiers (first-price RTB allocation proxy)
    tier_weights: list[float] = []
    for tier in _SYNTHETIC_SUPPLY_TIERS:
        res = interp.evaluate(tier["row"])
        score = res.score if (res.score is not None and not res.is_excluded and res.error is None) else 0.0
        # Value-per-euro drives DSP pacing allocation (sharpened by power 2.0 for competitive auction clearing)
        vpe = max(0.0, score / tier["cpm"])
        tier_weights.append(vpe ** 2.0)

    total_weight = sum(tier_weights)
    if total_weight <= 0.0:
        # Fallback uniform if script returns all zeros
        tier_weights = [1.0] * len(_SYNTHETIC_SUPPLY_TIERS)
        total_weight = float(len(_SYNTHETIC_SUPPLY_TIERS))

    total_imps = 0.0
    mfa_imps = 0.0
    editorial_imps = 0.0
    total_real_dwell_s = 0.0

    for tier, w in zip(_SYNTHETIC_SUPPLY_TIERS, tier_weights):
        spend_share = w / total_weight
        tier_spend = budget * spend_share
        imps = (tier_spend / tier["cpm"]) * 1000.0
        total_imps += imps
        if tier["is_mfa"]:
            mfa_imps += imps
        if tier["is_editorial"]:
            editorial_imps += imps
        total_real_dwell_s += imps * tier["real_dwell_s"]

    clearing_cpm = (budget / total_imps) * 1000.0 if total_imps > 0 else 0.0
    avg_dwell = total_real_dwell_s / total_imps if total_imps > 0 else 0.0
    mfa_share = (mfa_imps / total_imps) * 100.0 if total_imps > 0 else 0.0
    ed_share = (editorial_imps / total_imps) * 100.0 if total_imps > 0 else 0.0
    attentive_hours = total_real_dwell_s / 3600.0
    cost_per_1k_s = (budget / (total_real_dwell_s / 1000.0)) if total_real_dwell_s > 0 else 0.0

    eff_vs_vcpm = (
        ((vcpm_cost_per_1k_s - cost_per_1k_s) / vcpm_cost_per_1k_s) * 100.0
        if (vcpm_cost_per_1k_s is not None and vcpm_cost_per_1k_s > 0)
        else 0.0
    )

    return MfaStressTestStrategyResult(
        strategy_name=name,
        clearing_cpm=round(clearing_cpm, 2),
        impressions=round(total_imps, 0),
        avg_real_dwell_seconds=round(avg_dwell, 2),
        mfa_share_pct=round(mfa_share, 1),
        editorial_share_pct=round(ed_share, 1),
        attentive_hours=round(attentive_hours, 1),
        cost_per_1k_attentive_seconds=round(cost_per_1k_s, 2),
        efficiency_vs_vcpm_pct=round(eff_vs_vcpm, 1),
    )


def run_mfa_stress_test(
    script_code: str | None = None,
    *,
    budget: float = 100_000.0,
    config: ConcaveAttentionConfig | None = None,
    currency: str = "EUR",
) -> MfaStressTestReport:
    """Runs the 4-strategy sticky-MFA stress test using the safe ASTInterpreter."""
    strat_a_code = "return 1.0 if active_view_viewed else 0.0\n"
    strat_b_code = "return time_on_screen_seconds if active_view_viewed else 0.0\n"

    base_cfg = (config or ConcaveAttentionConfig()).model_copy(update={"excluded_domains": []})
    strat_c_code = compile_concave_attention_script(base_cfg, validate=True)

    mfa_cfg = base_cfg.model_copy(update={"excluded_domains": ["clickbait-slideshow-mfa.example"]})
    strat_d_code = compile_concave_attention_script(mfa_cfg, validate=True)

    res_a = _simulate_strategy("A: Standard vCPM", strat_a_code, budget)
    baseline_cost = res_a.cost_per_1k_attentive_seconds
    res_b = _simulate_strategy("B: Naive Uncapped Linear Dwell", strat_b_code, budget, baseline_cost)
    res_c = _simulate_strategy("C: Concave Capped + Format", strat_c_code, budget, baseline_cost)
    res_d = _simulate_strategy("D: Concave + MFA Exclusion", strat_d_code, budget, baseline_cost)

    strategies = [res_a, res_b, res_c, res_d]
    if script_code is not None:
        strategies.append(
            _simulate_strategy("Custom Script", script_code, budget, baseline_cost)
        )

    return MfaStressTestReport(
        budget=round(budget, 2),
        currency=currency.upper(),
        strategies=strategies,
    )
