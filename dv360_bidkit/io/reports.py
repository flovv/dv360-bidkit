def _detect_header_skiprows(path_obj: Path, sep: str, expected_cols: set[str]) -> int:
    """Scans the first 35 lines of a CSV/TSV file to locate the actual table header row."""
    expected_lower = {c.strip().lower() for c in expected_cols if c}
    for alias_list in COMMON_DV360_HEADER_ALIASES.values():
        for a in alias_list:
            expected_lower.add(a.lower())

    try:
        with open(path_obj, "r", encoding="utf-8-sig", errors="replace") as f:
            reader = csv.reader(f, delimiter=sep)
            for idx, row in enumerate(reader):
                if idx > 35:
                    break
                row_clean = {cell.strip().lower() for cell in row if cell and cell.strip()}
                # If at least 2 expected columns/aliases appear on this line, treat as header
                if len(row_clean & expected_lower) >= 2:
                    return idx
    except Exception:
        pass
    return 0


def _clean_numeric_series(series: pd.Series, *, is_integer_metric: bool = False) -> pd.Series:
    """Cleans locale-formatted numbers, thousand separators, currency symbols, and percentages.
    
    Robustly handles:
    - European formatting (e.g. '1.234.567,89', '1.234,56', '1.234.567')
    - US formatting (e.g. '1,234,567.89', '1,234.56')
    - Privacy-suppressed values (e.g. '< 100', '<10', '< 5', '*', '(not set)') -> converted to np.nan
    - Non-breaking spaces and currency symbols (€, $, £, CHF)
    """
    if pd.api.types.is_numeric_dtype(series):
        return series

    def _parse_val(v: Any) -> Any:
        if v is None or (isinstance(v, float) and pd.isna(v)):
            return v
        s = str(v).strip()
        if not s or s in (
            "-",
            "--",
            "N/A",
            "n/a",
            "null",
            "NULL",
            "None",
            "*",
            "**",
            "(not set)",
            "(not provided)",
            "(unavailable)",
            "unknown",
        ):
            return np.nan

        # Privacy-suppressed threshold values (e.g. "< 100", "<10", "< 5", "< 0.01%")
        if s.startswith("<") or s.startswith("≤"):
            return np.nan

        is_pct = s.endswith("%")
        if is_pct:
            s = s[:-1].strip()

        # Strip non-breaking spaces and regular spaces
        s = s.replace("\xa0", "").replace("\u202f", "").replace(" ", "")

        # Strip currency symbols
        for sym in ("$", "€", "£", "CHF", "USD", "EUR"):
            s = s.replace(sym, "")
        s = s.strip()

        if not s:
            return np.nan

        # Handle European vs US formatting:
        if "," in s and "." in s:
            if s.rfind(",") > s.rfind("."):
                # "1.234.567,89" or "1.234,56" -> period is thousand, comma is decimal
                s = s.replace(".", "").replace(",", ".")
            else:
                # "1,234,567.89" -> comma is thousand, period is decimal
                s = s.replace(",", "")
        elif "," in s:
            # Check if comma is a 3-digit thousand separator (e.g. "12,345" vs decimal "12,34")
            parts = s.split(",")
            if len(parts) > 1 and all(len(p) == 3 and p.isdigit() for p in parts[1:]):
                s = s.replace(",", "")
            else:
                s = s.replace(",", ".")
        elif "." in s:
            # Check if period is used as thousand separator without comma (e.g. "1.234.567" or "100.000")
            parts = s.split(".")
            if len(parts) > 1 and all(len(p) == 3 and p.isdigit() for p in parts[1:]):
                if is_integer_metric or len(parts) > 2:
                    s = s.replace(".", "")

        try:
            num = float(s)
            return num / 100.0 if is_pct else num
        except ValueError:
            return np.nan

    cleaned = series.map(_parse_val)
    try:
        return pd.to_numeric(cleaned)
    except (ValueError, TypeError):
        return cleaned


def _strip_footer_and_summary_rows(df: pd.DataFrame) -> tuple[pd.DataFrame, int]:
    """Removes DV360 summary/total rows and trailing metadata footers."""
    if df.empty:
        return df, 0

    initial_len = len(df)
    first_col = df.columns[0]

    # Identify rows where the first column is an exact summary marker or metadata prefix
    keep_mask = pd.Series(True, index=df.index)
    for idx, row in df.iterrows():
        val0 = row[first_col]
        if pd.isna(val0):
            if row.isna().all():
                keep_mask.loc[idx] = False
            continue
        s0 = str(val0).strip().lower()
        if s0 in SUMMARY_EXACT_MARKERS or any(s0.startswith(p) for p in SUMMARY_PREFIX_MARKERS):
            keep_mask.loc[idx] = False
        elif len(df.columns) > 1 and row.iloc[1:].isna().all():
            # Single-cell disclaimer/footer row
            keep_mask.loc[idx] = False

    filtered = df[keep_mask].reset_index(drop=True)
    return filtered, initial_len - len(filtered)


def load_report(
    path: str | Path,
    *,
    mapping: ReportMapping,
) -> ReportData:
    """Loads and validates a customer report file with an explicit mapping.

    Automatically strips DV360 preamble metadata rows and summary footer rows,
    cleans locale-formatted numbers/percentages, resolves header aliases,
    and validates denominator consistency.

    Parameters
    ----------
    path : str | Path
        Path to CSV or TSV report file.
    mapping : ReportMapping
        Column mapping and denominator validation settings.

    Returns
    -------
    ReportData
        Validated pandas DataFrame with associated metadata.
    """
    path_obj = Path(path)
    if not path_obj.exists():
        raise FileNotFoundError(f"Report file not found: {path}")

    sep = "\t" if path_obj.suffix.lower() == ".tsv" else ","
    expected_cols = set(mapping.canonical_field_map.values())
    skiprows = _detect_header_skiprows(path_obj, sep, expected_cols)

    try:
        df = pd.read_csv(path_obj, sep=sep, encoding="utf-8-sig", skiprows=skiprows, dtype=str)
    except Exception as exc:
        raise ReportMappingError(f"Failed to read report file {path}: {exc}") from exc

    # Strip whitespace from column names
    df.columns = [str(c).strip() for c in df.columns]

    # Strip summary/footer rows
    df, stripped_rows = _strip_footer_and_summary_rows(df)

    # Resolve column mappings (exact -> case-insensitive -> known DV360 EN/DE header alias)
    col_lookup_lower = {c.lower(): c for c in df.columns}
    resolved_field_map = dict(mapping.canonical_field_map)
    missing_cols = []

    for canonical, source_col in mapping.canonical_field_map.items():
        if source_col in df.columns:
            continue
        if source_col.strip().lower() in col_lookup_lower:
            resolved_field_map[canonical] = col_lookup_lower[source_col.strip().lower()]
            continue
        # Check common DV360 aliases for this canonical field
        alias_matched = None
        for alias in COMMON_DV360_HEADER_ALIASES.get(canonical, []):
            if alias.lower() in col_lookup_lower:
                alias_matched = col_lookup_lower[alias.lower()]
                break
        if alias_matched is not None:
            resolved_field_map[canonical] = alias_matched
        else:
            missing_cols.append(f"canonical '{canonical}' -> missing column '{source_col}'")

    if missing_cols:
        raise ReportMappingError(
            f"Report file {path} missing mapped columns:\n" + "\n".join(missing_cols)
        )

    # Clean numeric columns mapped in canonical_field_map or denominators
    numeric_cols_to_clean: set[str] = set()
    for canonical, col_name in resolved_field_map.items():
        if canonical in NUMERIC_CANONICAL_FIELDS and col_name in df.columns:
            numeric_cols_to_clean.add(col_name)
    for num_key, denom_key in mapping.denominators.items():
        for k in (num_key, denom_key):
            c = resolved_field_map.get(k, k)
            if c in df.columns:
                numeric_cols_to_clean.add(c)

    for col_name in numeric_cols_to_clean:
        canon = None
        for k, v in resolved_field_map.items():
            if v == col_name:
                canon = k
                break
        is_int_m = canon in INTEGER_CANONICAL_FIELDS
        df[col_name] = _clean_numeric_series(df[col_name], is_integer_metric=is_int_m)

    # Convert non-metric columns containing integer digits (e.g. IDs, device_type, environment)
    for col in df.columns:
        if col not in numeric_cols_to_clean:
            non_null = df[col].dropna()
            if not non_null.empty and non_null.astype(str).str.isdigit().all():
                try:
                    df[col] = df[col].astype(int)
                except (ValueError, TypeError):
                    pass

    # Update mapping with resolved column names if any alias/case-folding occurred
    effective_mapping = mapping.model_copy(update={"canonical_field_map": resolved_field_map})

    # Denominator validation
    # e.g. viewable_impressions <= measurable_impressions <= impressions
    imp_col = resolved_field_map.get("impressions")
    meas_col = resolved_field_map.get("measurable_impressions")
    view_col = resolved_field_map.get("viewable_impressions")

    if imp_col and meas_col and imp_col in df.columns and meas_col in df.columns:
        invalid_meas = df[df[meas_col] > df[imp_col]]
        if not invalid_meas.empty:
            raise ReportMappingError(
                f"Denominator violation: {len(invalid_meas)} rows have measurable impressions > total impressions."
            )

    if meas_col and view_col and meas_col in df.columns and view_col in df.columns:
        invalid_view = df[df[view_col] > df[meas_col]]
        if not invalid_view.empty:
            raise ReportMappingError(
                f"Denominator violation: {len(invalid_view)} rows have viewable impressions > measurable impressions."
            )

    return ReportData(
        df=df,
        mapping=effective_mapping,
        metadata={
            "source_path": str(path_obj),
            "row_count": len(df),
            "columns": list(df.columns),
            "grain": effective_mapping.row_grain.value,
            "preamble_rows_skipped": skiprows,
            "footer_rows_stripped": stripped_rows,
        },
    )
